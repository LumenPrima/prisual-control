package streamdeck

import (
	"image"
	"image/color"
	"strings"
)

const (
	charW    = 5
	charH    = 7
	fontScale = 2
	charGap  = 1 // pixel gap between chars (at base scale)
)

// drawText renders a label centered on the image using a built-in 5x7 bitmap font.
// Supports multi-line text separated by "\n". Each line is centered independently.
func drawText(img *image.RGBA, text string, fg color.RGBA, rect image.Rectangle) {
	lines := strings.Split(text, "\n")

	scaledH := charH * fontScale
	lineGap := 4 * fontScale // gap between lines
	totalH := len(lines)*scaledH + (len(lines)-1)*lineGap

	baseY := rect.Min.Y + (rect.Dy()-totalH)/2

	for li, line := range lines {
		if line == "" {
			continue
		}
		lineY := baseY + li*(scaledH+lineGap)
		drawLine(img, line, fg, rect, lineY)
	}
}

// drawLine renders a single line of text horizontally centered at the given Y position.
func drawLine(img *image.RGBA, text string, fg color.RGBA, rect image.Rectangle, startY int) {
	scaledW := charW * fontScale
	scaledGap := charGap * fontScale
	totalW := len(text)*scaledW + (len(text)-1)*scaledGap
	if totalW <= 0 {
		return
	}

	startX := rect.Min.X + (rect.Dx()-totalW)/2

	for i, ch := range text {
		glyph := getGlyph(byte(ch))
		ox := startX + i*(scaledW+scaledGap)
		for row := 0; row < charH; row++ {
			for col := 0; col < charW; col++ {
				if glyph[row]&(1<<(charW-1-col)) != 0 {
					for sy := 0; sy < fontScale; sy++ {
						for sx := 0; sx < fontScale; sx++ {
							px := ox + col*fontScale + sx
							py := startY + row*fontScale + sy
							if px >= rect.Min.X && px < rect.Max.X && py >= rect.Min.Y && py < rect.Max.Y {
								img.SetRGBA(px, py, fg)
							}
						}
					}
				}
			}
		}
	}
}

// getGlyph returns a 7-row bitmap for a character. Each byte has 5 bits (MSB-aligned).
func getGlyph(ch byte) [7]byte {
	if g, ok := font5x7[ch]; ok {
		return g
	}
	return font5x7['?']
}

